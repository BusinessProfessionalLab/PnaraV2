// Collect the Astro source's CSS into one stylesheet for the Next build:
// next/src/styles/site.css.
//
// Order: src/styles/global.css (with its @imports inlined), then every
// component's <style> block: components, sections, layouts, pages. Comments
// are kept. (Parley keeps every rule in src/styles today, so the component
// pass finds nothing; it is here so a <style> added later is carried over.)
//
// Astro scopes component styles; one flat file does not. So every component's
// selectors must start with a class only that component uses. The script
// refuses to write the file when a root class appears in two components, or in
// a component and the global sheets, since that is exactly where one rule
// would start restyling something else.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const A = join(ROOT, 'src');
const OUT = join(ROOT, 'next', 'src', 'styles', 'site.css');
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));

function inline(file) {
  return readFileSync(file, 'utf8').replace(/@import\s+['"](.+?)['"];?/g, (_, p) => inline(join(dirname(file), p)));
}
const rootClasses = (css) => {
  const out = [];
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of bare.matchAll(/(?<=^|[{};])([^{};]+)\{/g)) {
    const sel = m[1].trim();
    if (!sel || sel.startsWith('@')) continue;
    for (const one of sel.split(',')) {
      const s = one.trim();
      if (!s || /^(from|to|\d+%)$/.test(s)) continue;
      out.push([s, s.match(/\.([A-Za-z_][\w-]*)/)?.[1]]);
    }
  }
  return out;
};

const global = inline(join(A, 'styles', 'global.css'));
const globalOwned = new Set(rootClasses(global).map(([, c]) => c).filter(Boolean));

const ORDER = ['components/sections', 'components', 'layouts', 'pages'];
const files = walk(A).filter((f) => f.endsWith('.astro'))
  .map((f) => relative(A, f).replace(/\\/g, '/'))
  .sort((a, b) => {
    const ia = ORDER.findIndex((o) => a.startsWith(o + '/')), ib = ORDER.findIndex((o) => b.startsWith(o + '/'));
    return ia - ib || a.localeCompare(b);
  });

const owners = new Map();
const problems = [];
const parts = ['/* GENERATED by tools/collect-css.mjs from src/styles (Astro). Edit the Astro source, then regenerate. */', global];

for (const rel of files) {
  const src = readFileSync(join(A, rel), 'utf8');
  for (const [, attrs = '', css] of src.matchAll(/<style(\s[^>]*)?>([\s\S]*?)<\/style>/g)) {
    if (/is:global|define:vars|is:inline/.test(attrs)) problems.push(`${rel}: <style${attrs}> is not allowed`);
    if (/:global\(/.test(css)) problems.push(`${rel}: :global() is not allowed`);
    for (const [s, root] of rootClasses(css)) {
      if (!root) { problems.push(`${rel}: selector without a component class: "${s}"`); continue; }
      if (globalOwned.has(root)) { problems.push(`${rel}: .${root} is also styled in src/styles`); continue; }
      const prev = owners.get(root);
      if (prev && prev !== rel) problems.push(`.${root} is styled in both ${prev} and ${rel}`);
      else owners.set(root, rel);
    }
    parts.push(`/* ---- ${rel} ---- */\n${css.trim()}`);
  }
}

if (problems.length) {
  console.error('collect-css refused:\n  ' + [...new Set(problems)].join('\n  '));
  process.exit(1);
}
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, parts.join('\n\n') + '\n');
console.log(`${files.length} .astro files scanned, ${owners.size} component classes -> ${relative(ROOT, OUT)}`);
